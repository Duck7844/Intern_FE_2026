"use client";

import Link from "next/link";
import { useRouter } from "next/navigation";
import { useEffect, useState, type FormEvent } from "react";
import { Markdown } from "@/components/blog/markdown";
import { adminApi } from "@/lib/api/admin";
import { isApiError } from "@/lib/api/http";
import type { PostDetail, PostInput } from "@/types/api";
import { ImageUpload } from "./image-upload";
import { Card, Field, LoadingBlock, Notice, PageHeader, Spinner, errorMessage, fieldClass } from "./ui";

const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

type Values = {
  title: string;
  slug: string;
  excerpt: string;
  content: string;
  thumbnailUrl: string | null;
  published: boolean;
};

type Errors = Partial<Record<keyof Values, string>>;

function validate(values: Values, slugEdited: boolean): Errors {
  const errors: Errors = {};
  const title = values.title.trim();
  if (!title) errors.title = "Title is required";
  else if (title.length > 200) errors.title = "Title must be 200 characters or less";
  if (slugEdited && values.slug.trim() && !SLUG_RE.test(values.slug.trim())) {
    errors.slug = "Use lowercase letters, numbers and single hyphens only";
  }
  if (values.excerpt.length > 500) errors.excerpt = "Excerpt must be 500 characters or less";
  if (!values.content.trim()) errors.content = "Content is required";
  else if (values.content.length > 100000) errors.content = "Content is too long (max 100,000 characters)";
  return errors;
}

/** Create or edit a post. Edit mode loads the post first (drafts included). */
export function PostForm({ postId }: { postId?: string }) {
  const router = useRouter();
  const editing = Boolean(postId);
  const [post, setPost] = useState<PostDetail | null>(null);
  const [loadError, setLoadError] = useState<string | null>(null);
  const [values, setValues] = useState<Values>({ title: "", slug: "", excerpt: "", content: "", thumbnailUrl: null, published: false });
  const [slugEdited, setSlugEdited] = useState(false);
  const [errors, setErrors] = useState<Errors>({});
  const [busy, setBusy] = useState(false);
  const [notice, setNotice] = useState<{ tone: "success" | "error"; text: string } | null>(null);
  const [preview, setPreview] = useState(false);

  useEffect(() => {
    if (!postId) return;
    let cancelled = false;
    adminApi.posts
      .get(postId)
      .then((p) => {
        if (cancelled) return;
        setPost(p);
        setValues({
          title: p.title,
          slug: p.slug,
          excerpt: p.excerpt ?? "",
          content: p.content,
          thumbnailUrl: p.thumbnailUrl,
          published: p.published,
        });
      })
      .catch((e: unknown) => !cancelled && setLoadError(isApiError(e) && e.status === 404 ? "This post does not exist." : errorMessage(e)));
    return () => {
      cancelled = true;
    };
  }, [postId]);

  function set<K extends keyof Values>(key: K, value: Values[K]) {
    setValues((v) => ({ ...v, [key]: value }));
    if (errors[key]) setErrors((e) => ({ ...e, [key]: undefined }));
  }

  async function submit(publishedOverride?: boolean) {
    if (busy) return;
    const next = publishedOverride === undefined ? values : { ...values, published: publishedOverride };
    const nextErrors = validate(next, slugEdited);
    setErrors(nextErrors);
    if (Object.keys(nextErrors).length > 0) return;

    const input: PostInput = {
      title: next.title.trim(),
      excerpt: next.excerpt.trim() || null,
      content: next.content,
      thumbnailUrl: next.thumbnailUrl,
      published: next.published,
    };
    // Slug is generated by the API from the title and never changes on a
    // title edit; it is only sent when the admin typed one deliberately.
    if (slugEdited && next.slug.trim()) input.slug = next.slug.trim();

    setBusy(true);
    setNotice(null);
    try {
      if (editing && postId) {
        const saved = await adminApi.posts.update(postId, input);
        setPost(saved);
        setValues((v) => ({ ...v, slug: saved.slug, published: saved.published }));
        setSlugEdited(false);
        setNotice({ tone: "success", text: saved.published ? "Saved and published." : "Draft saved." });
      } else {
        const created = await adminApi.posts.create(input);
        router.replace(`/admin/posts/${created.id}/edit`);
      }
    } catch (e) {
      setNotice({ tone: "error", text: isApiError(e) ? e.messages.join(" ") : errorMessage(e, "Save failed") });
    } finally {
      setBusy(false);
    }
  }

  function onSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    void submit();
  }

  if (loadError) {
    return (
      <>
        <PageHeader title="Edit post" />
        <Notice tone="error">{loadError}</Notice>
        <Link href="/admin/posts" className="text-btn-xs text-brand hover:underline">
          ← Back to posts
        </Link>
      </>
    );
  }
  if (editing && !post) {
    return (
      <>
        <PageHeader title="Edit post" />
        <LoadingBlock rows={6} />
      </>
    );
  }

  return (
    <form onSubmit={onSubmit} noValidate aria-busy={busy} className="flex flex-col gap-6">
      <PageHeader
        title={editing ? "Edit post" : "New post"}
        description={editing && post ? `/blog/${post.slug}` : "The slug is generated automatically from the title."}
        actions={
          <>
            <Link href="/admin/posts" className="inline-flex h-10 items-center rounded-xs border border-stroke-bold bg-white px-4 text-btn-xs text-ink hover:bg-surface-a">
              Back
            </Link>
            {post?.published && (
              <a href={`/blog/${post.slug}`} target="_blank" rel="noreferrer" className="inline-flex h-10 items-center rounded-xs border border-stroke-bold bg-white px-4 text-btn-xs text-ink hover:bg-surface-a">
                View post
              </a>
            )}
          </>
        }
      />

      {notice && <Notice tone={notice.tone}>{notice.text}</Notice>}

      <div className="grid gap-6 lg:grid-cols-[1fr_320px]">
        <Card className="flex flex-col gap-5">
          <Field label="Title" htmlFor="post-title" error={errors.title} required>
            <input id="post-title" value={values.title} onChange={(e) => set("title", e.target.value)} maxLength={200} disabled={busy} aria-invalid={!!errors.title} className={`${fieldClass} h-11`} />
          </Field>

          <Field
            label="Slug"
            htmlFor="post-slug"
            error={errors.slug}
            hint={editing ? "Changing the slug breaks the old link. Leave as is to keep it." : "Leave empty to generate it from the title."}
          >
            <input
              id="post-slug"
              value={values.slug}
              onChange={(e) => {
                setSlugEdited(true);
                set("slug", e.target.value.toLowerCase());
              }}
              placeholder="example-post-slug"
              disabled={busy}
              aria-invalid={!!errors.slug}
              className={`${fieldClass} h-11 font-mono text-body3`}
            />
          </Field>

          <Field label="Excerpt" htmlFor="post-excerpt" error={errors.excerpt} hint={`${values.excerpt.length}/500 · shown in the post list and the Summary box`}>
            <textarea id="post-excerpt" value={values.excerpt} onChange={(e) => set("excerpt", e.target.value)} rows={3} maxLength={500} disabled={busy} aria-invalid={!!errors.excerpt} className={`${fieldClass} min-h-[88px] resize-y py-2.5`} />
          </Field>

          <div className="flex flex-col gap-1.5">
            <div className="flex items-center justify-between">
              <label htmlFor="post-content" className="text-body3 font-semibold text-ink">
                Content (Markdown) <span className="text-brand">*</span>
              </label>
              <div className="flex gap-1 text-caption">
                <button type="button" onClick={() => setPreview(false)} className={`rounded-label px-2 py-1 ${!preview ? "bg-ink text-white" : "text-ink-secondary hover:text-ink"}`}>
                  Write
                </button>
                <button type="button" onClick={() => setPreview(true)} className={`rounded-label px-2 py-1 ${preview ? "bg-ink text-white" : "text-ink-secondary hover:text-ink"}`}>
                  Preview
                </button>
              </div>
            </div>
            {preview ? (
              <div className="min-h-[420px] rounded-xs border border-stroke-light bg-white p-4">
                {values.content.trim() ? <Markdown content={values.content} /> : <p className="text-body3 text-ink-tertiary">Nothing to preview yet.</p>}
              </div>
            ) : (
              <textarea
                id="post-content"
                value={values.content}
                onChange={(e) => set("content", e.target.value)}
                rows={18}
                disabled={busy}
                aria-invalid={!!errors.content}
                placeholder={"## Heading\n\nWrite the post in Markdown. Image: ![description](/uploads/....jpg)"}
                className={`${fieldClass} min-h-[420px] resize-y py-2.5 font-mono text-body3 leading-6`}
              />
            )}
            {errors.content ? <p className="text-caption text-brand">{errors.content}</p> : <p className="text-caption text-ink-secondary">GitHub-flavored Markdown is supported. Raw HTML is ignored when rendering.</p>}
          </div>
        </Card>

        <div className="flex flex-col gap-6">
          <Card className="flex flex-col gap-4">
            <h2 className="text-body1 font-bold text-ink">Publishing</h2>
            <label className="flex items-center gap-3 text-body3 text-ink">
              <input type="checkbox" checked={values.published} onChange={(e) => set("published", e.target.checked)} disabled={busy} className="size-4 accent-brand" />
              Published (visible on the website)
            </label>
            <div className="flex flex-col gap-2">
              <button type="submit" disabled={busy} className="inline-flex h-10 items-center justify-center gap-2 rounded-xs bg-brand px-4 text-btn-xs text-white hover:bg-brand-dark disabled:opacity-50">
                {busy && <Spinner />}
                {editing ? "Save changes" : "Create post"}
              </button>
              {!values.published && (
                <button type="button" disabled={busy} onClick={() => void submit(true)} className="inline-flex h-10 items-center justify-center rounded-xs border border-stroke-bold bg-white px-4 text-btn-xs text-ink hover:bg-surface-a disabled:opacity-50">
                  {editing ? "Save & publish" : "Create & publish"}
                </button>
              )}
            </div>
          </Card>

          <Card>
            <ImageUpload label="Thumbnail" value={values.thumbnailUrl} onChange={(url) => set("thumbnailUrl", url)} disabled={busy} />
          </Card>
        </div>
      </div>
    </form>
  );
}
